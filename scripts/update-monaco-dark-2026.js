import fs from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const VSCODE_COMMIT = '53e9983e61535999978c09e080fedfe3356309ed'
const THEME_ROOT = `https://raw.githubusercontent.com/microsoft/vscode/${VSCODE_COMMIT}/extensions/theme-defaults/themes`
const ENTRY = '2026-dark.json'
const outputPath = fileURLToPath(
  new URL('../src/editor/themes/dark2026.js', import.meta.url),
)

const stripJsonComments = (source) => {
  let result = ''
  let inString = false
  let escaped = false

  for (let index = 0; index < source.length; index += 1) {
    const character = source[index]
    const next = source[index + 1]

    if (inString) {
      result += character
      if (escaped) escaped = false
      else if (character === '\\') escaped = true
      else if (character === '"') inString = false
      continue
    }
    if (character === '"') {
      inString = true
      result += character
      continue
    }
    if (character === '/' && next === '/') {
      while (index < source.length && source[index] !== '\n') index += 1
      result += '\n'
      continue
    }
    if (character === '/' && next === '*') {
      index += 2
      while (
        index < source.length &&
        !(source[index] === '*' && source[index + 1] === '/')
      ) index += 1
      index += 1
      continue
    }
    result += character
  }

  return result.replace(/,\s*([}\]])/g, '$1')
}

const loadTheme = async (fileName, chain = []) => {
  if (chain.includes(fileName)) {
    throw new Error(`Circular VS Code theme include: ${[...chain, fileName].join(' -> ')}`)
  }
  const response = await fetch(`${THEME_ROOT}/${fileName}`)
  if (!response.ok) {
    throw new Error(`Unable to download ${fileName}: HTTP ${response.status}`)
  }
  const current = JSON.parse(stripJsonComments(await response.text()))
  const parentName = current.include
    ? path.posix.normalize(path.posix.join(path.posix.dirname(fileName), current.include))
    : null
  const parent = parentName
    ? await loadTheme(parentName, [...chain, fileName])
    : { colors: {}, tokenColors: [], semanticTokenColors: {} }

  return {
    colors: { ...parent.colors, ...(current.colors || {}) },
    tokenColors: [...parent.tokenColors, ...(current.tokenColors || [])],
    semanticTokenColors: {
      ...parent.semanticTokenColors,
      ...(current.semanticTokenColors || {}),
    },
    semanticHighlighting:
      current.semanticHighlighting ?? parent.semanticHighlighting ?? true,
    includeChain: [...(parent.includeChain || []), fileName],
  }
}

const normalizeColor = (color) =>
  typeof color === 'string' ? color.replace(/^#/, '') : undefined

const textMateRules = (tokenColors) => tokenColors.flatMap(({ scope, settings = {} }) => {
  const scopes = Array.isArray(scope) ? scope : [scope]
  return scopes.filter(Boolean).map((token) => ({
    token,
    ...(settings.foreground ? { foreground: normalizeColor(settings.foreground) } : {}),
    ...(settings.background ? { background: normalizeColor(settings.background) } : {}),
    ...(settings.fontStyle !== undefined ? { fontStyle: settings.fontStyle } : {}),
  }))
})

const semanticRules = (semanticTokenColors) =>
  Object.entries(semanticTokenColors).flatMap(([token, value]) => {
    if (typeof value === 'string') {
      return [{ token, foreground: normalizeColor(value) }]
    }
    if (!value || typeof value !== 'object') return []
    const fontStyle = [
      value.bold && 'bold',
      value.italic && 'italic',
      value.underline && 'underline',
      value.strikethrough && 'strikethrough',
    ].filter(Boolean).join(' ')
    return [{
      token,
      ...(value.foreground ? { foreground: normalizeColor(value.foreground) } : {}),
      ...(fontStyle ? { fontStyle } : {}),
    }]
  })

const theme = await loadTheme(ENTRY)
const monacoTheme = {
  base: 'vs-dark',
  inherit: false,
  rules: [
    ...textMateRules(theme.tokenColors),
    ...semanticRules(theme.semanticTokenColors),
  ],
  colors: theme.colors,
}
const source = `// Generated by scripts/update-monaco-dark-2026.js. Do not edit by hand.
// Source: microsoft/vscode@${VSCODE_COMMIT} (MIT), extensions/theme-defaults/themes/${ENTRY}
// Include chain: ${theme.includeChain.join(' -> ')}

export const VESPERWIND_DARK_2026_THEME_ID = 'vesperwind-dark-2026'

export const dark2026Theme = Object.freeze(${JSON.stringify(monacoTheme, null, 2)})
`

await fs.mkdir(path.dirname(outputPath), { recursive: true })
await fs.writeFile(outputPath, source)
console.log(`Wrote ${outputPath}`)
console.log(`Resolved ${theme.includeChain.join(' -> ')}`)
console.log(`Converted ${monacoTheme.rules.length} token rules`)
